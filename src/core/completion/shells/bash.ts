/**
 * Bash completion script generator.
 *
 * Produces a self-contained bash script with:
 * - A main `_<name>_completions` function using `COMP_WORDS`/`COMP_CWORD`
 * - Multi-level subcommand path detection via progressive COMP_WORDS scanning
 * - Per-command case branches with flag and subcommand completions
 * - Propagated flags from ancestor commands at each nesting level
 * - Enum value completions for `--flag=<value>` patterns
 * - A `complete -F` registration line
 *
 * **Requires** the `bash-completion` package (`_init_completion`).
 *
 * @module dreamcli/core/completion/shells/bash
 * @internal
 */

import { BUILTIN_SPECS, builtinEnabled } from '#internals/core/cli/builtins.ts';
import type { CLISchema } from '#internals/core/cli/index.ts';
import { buildFlagLookup, flagExpectsValue } from '#internals/core/parse/index.ts';
import { getFlagAliasNames } from '#internals/core/schema/flag.ts';
import type { CommandSchema, FlagSchema } from '#internals/core/schema/index.ts';
import { acceptsArgv } from '#internals/core/schema/stdin.ts';
import type { CommandNode, CompletionOptions } from './shared.ts';
import {
	getVisibleNegatedName,
	hasDynamicCompletion,
	programTag,
	quoteShellArg,
	resolveRootCompletionSurface,
	sanitizeShellIdentifier,
	staticFlagCandidates,
	versionTag,
	walkCommandTree,
} from './shared.ts';

// --- Public generator

/**
 * Generate a bash completion script for the CLI.
 *
 * Use this when you want a bash-specific script directly rather than routing
 * through {@link generateCompletion}. The generated script expects the
 * `bash-completion` package because it relies on `_init_completion`.
 *
 * @param schema - The CLI schema.
 * @param options - Optional generator configuration.
 * @returns A complete bash completion script.
 *
 * @example
 * ```ts
 * const script = generateBashCompletion(app.schema);
 * // install with: mycli completions bash > /etc/bash_completion.d/mycli
 * ```
 */
function generateBashCompletion(schema: CLISchema, options?: CompletionOptions): string {
	const prefix = options?.functionPrefix ?? schema.name;
	const funcName = `_${sanitizeShellIdentifier(prefix)}_completions`;
	const rootSurface = resolveRootCompletionSurface(schema, options?.rootMode);
	const visibleCommands = rootSurface.visibleCommands;
	const nodes = walkCommandTree(visibleCommands);
	const rootFlags = {
		...rootSurface.rootFlags,
		...(rootSurface.includeDefaultFlags ? rootSurface.defaultFlags : {}),
	};
	const rootScanFlags = rootSurface.defaultFlags;
	const helpEnabled = builtinEnabled(schema.builtins, 'help');
	const config = schema.configSettings;
	const outputPatterns = (['json', 'quiet'] as const)
		.filter((name) => builtinEnabled(schema.builtins, name))
		.flatMap((name) => {
			const { long, short } = BUILTIN_SPECS[name];
			return [
				...short.map(escapeBashCasePatternValue),
				...long.flatMap((spelling) => {
					const pattern = escapeBashCasePatternValue(spelling);
					return [pattern, `${pattern}=*`];
				}),
			];
		});
	const hasPreflight = config !== undefined || outputPatterns.length > 0;
	const reservedOperands = [
		...outputPatterns,
		...(config?.noConfigFlag === true ? ['--no-config'] : []),
		...(schema.version === undefined
			? []
			: ['--version', escapeBashCasePatternValue(`-${schema.versionAlias ?? 'V'}`)]),
		...(schema.completionsFlag === undefined ? [] : ['--completions', '--completions=*']),
	];
	const dynamicCompletion = hasDynamicCompletion(schema);

	const lines: string[] = [];

	lines.push(`#!/usr/bin/env bash
# Bash completion for ${programTag(schema)}
# Generated by ${versionTag()}
#
# Usage:  source <(${schema.name} completions bash)
#
# Install permanently:
#   ${schema.name} completions bash > /etc/bash_completion.d/${schema.name}    # Linux
#   ${schema.name} completions bash > $(brew --prefix)/etc/bash_completion.d/${schema.name}  # macOS
#
# Requires: bash-completion (provides _init_completion)
`);
	emitBashReadlineHelpers(lines, funcName);
	// Readline replaces its own word fragment, even when _init_completion rejoins split tokens.
	lines.push(`${funcName}() {
	local cur prev words cword
	_init_completion -n =:/, || return
	COMPREPLY=()
	local readline_prefix="" readline_quote="" unquoted quote word
	if [[ $# -ge 2 && "$cur" == *"$2" ]]; then
		readline_prefix="\${cur%"$2"}"
	fi
	${funcName}_unquote "$readline_prefix"
	readline_prefix="$unquoted" readline_quote="$quote"
	local -a argv=()
	for word in "\${words[@]:1:cword-1}" "$cur"; do
		${funcName}_unquote "$word"
		argv+=("$unquoted")
	done
	cur="$unquoted"`);
	if (dynamicCompletion) {
		lines.push('\tlocal dynamic candidate');
		lines.push(
			`\tif dynamic=$(command ${quoteShellArg(schema.name)} __complete -- "\${argv[@]}" 2>/dev/null); then`,
		);
		lines.push('\t\twhile IFS= read -r candidate; do');
		lines.push('\t\t\t[[ -n "$candidate" ]] || continue');
		lines.push(`\t\t\t${funcName}_reply "$candidate"`);
		lines.push('\t\tdone <<< "$dynamic"');
		lines.push('\t\treturn');
		lines.push('\tfi');
	}
	lines.push('');

	emitBashOptionScan(lines, funcName, nodes.length > 0, hasPreflight, config);
	if (visibleCommands.length > 0) {
		// Per-path completions: one case branch per node
		lines.push('\t# Complete flags and subcommands for the active path');
		lines.push('\tcase "$subcmd_path" in');

		for (const node of nodes) {
			const pathKey = node.path.join(' ');
			const mergedFlags = node.mergedFlags;
			const flagWords = collectFlagWords(mergedFlags);
			const childNames = dedupeWords(
				node.children.flatMap((child) => [child.name, ...child.aliases]),
			)
				.map(escapeForSingleQuote)
				.join(' ');
			const escapedFlagWords = flagWords
				.split(' ')
				.filter(Boolean)
				.map(escapeForSingleQuote)
				.join(' ');
			const completionWords =
				childNames.length > 0 ? `${childNames} ${escapedFlagWords}` : escapedFlagWords;

			lines.push(`\t\t${quoteShellCasePattern(pathKey)})`);

			emitBashValueCompletions(
				lines,
				funcName,
				mergedFlags,
				'\t\t\t',
				helpEnabled ? node.schema.helpTopics : undefined,
			);

			lines.push(`\t\t\tCOMPREPLY=($(compgen -W '${completionWords.trim()}' -- "$cur"))`);
			lines.push('\t\t\treturn');
			lines.push('\t\t\t;;');
		}

		lines.push('\t\t*)');
		lines.push('\t\t\t;;');
		lines.push('\tesac');
		lines.push('');
	}

	emitBashValueCompletions(
		lines,
		funcName,
		rootFlags,
		'\t',
		helpEnabled ? rootSurface.visibleDefaultCommand?.helpTopics : undefined,
	);
	const rootWords = dedupeWords([
		...visibleCommands.flatMap((command) => [command.name, ...command.aliases]),
		...collectFlagWords(rootFlags).split(' ').filter(Boolean),
	])
		.map(escapeForSingleQuote)
		.join(' ');
	lines.push(`\tCOMPREPLY=($(compgen -W '${rootWords}' -- "$cur"))`);

	lines.push('}');
	lines.push('');
	emitBashOptionHelpers(
		lines,
		funcName,
		rootScanFlags,
		nodes,
		schema.flagSettings,
		config,
		reservedOperands,
	);
	if (hasPreflight) emitBashPreflightFilter(lines, funcName, config, outputPatterns);
	if (nodes.length > 0) {
		emitBashPathDetection(lines, funcName, visibleCommands, nodes, hasPreflight);
	}
	lines.push(`complete -F ${funcName} ${quoteShellArg(schema.name)}`);
	lines.push('');

	return lines.join('\n');
}

// --- Bash helpers — internal

/** Decode shell words and insert candidates into Readline's replacement range. */
function emitBashReadlineHelpers(lines: string[], funcName: string): void {
	lines.push(`${funcName}_unquote() {
	local text="$1" char escaped=0 i
	unquoted="" quote=""
	for ((i = 0; i < \${#text}; i++)); do
		char="\${text:i:1}"
		if ((escaped)); then
			[[ "$quote" == '"' && "$char" != [\\\\\\"\\$\\\`] ]] && unquoted+='\\'
			unquoted+="$char"; escaped=0
		elif [[ "$char" == '\\' && "$quote" != "'" ]]; then
			escaped=1
		elif [[ -n "$quote" ]]; then
			if [[ "$char" == "$quote" ]]; then quote=""; else unquoted+="$char"; fi
		elif [[ "$char" == "'" || "$char" == '"' ]]; then
			quote="$char"
		else
			unquoted+="$char"
		fi
	done
	((escaped)) && unquoted+='\\'
	return 0
}

${funcName}_reply() {
	local candidate="\${1#"$readline_prefix"}" quoted char i
	compopt -o noquote 2>/dev/null || :
	if [[ -z "$readline_quote" ]]; then
		printf -v candidate %q "$candidate"
	else
		quoted="$readline_quote"
		for ((i = 0; i < \${#candidate}; i++)); do
			char="\${candidate:i:1}"
			if [[ "$readline_quote" == '"' && "$char" == ! ]]; then quoted+='"\\!"'; continue; fi
			if [[ "$readline_quote" == '"' && "$char" == [\\\\\\"\\$\\\`] ]]; then quoted+='\\'; fi
			if [[ "$readline_quote" == "'" && "$char" == "'" ]]; then quoted+="'\\\\''"; else quoted+="$char"; fi
		done
		candidate="$quoted"
	fi
	COMPREPLY+=("$candidate")
}
`);
}

/** Select the command scope, then match complete operands and the unfinished cursor word. */
function emitBashOptionScan(
	lines: string[],
	funcName: string,
	hasCommands: boolean,
	hasPreflight: boolean,
	config: CLISchema['configSettings'],
): void {
	lines.push(`	local subcmd_path="" cursor_index=$((cword - 1))
	local -a removed_words=()
	local i token option_spelling option_kind option_prefix
	local value_flag="" value_kind="" value_prefix="" first_variadic=0
	for ((i = 0; i < cursor_index; i++)); do
		[[ "\${argv[i]}" == -- ]] && return 0
	done`);
	if (config !== undefined) {
		lines.push('\tlocal config_seen=0 no_config_seen=0');
	}
	if (hasCommands) {
		lines.push('\tlocal resolved_path');
		lines.push(`\t${funcName}_route`);
		lines.push('\tsubcmd_path="$resolved_path"');
	} else if (hasPreflight) {
		lines.push(`\t${funcName}_filter_preflight`);
	}
	if (hasPreflight) {
		lines.push(`\t[[ -n "\${removed_words[cursor_index]-}" ]] && return 0`);
		if (config?.noConfigFlag === true)
			lines.push('\t((config_seen && no_config_seen)) && return 0');
	}
	lines.push(`
	for ((i = 0; i <= cursor_index; i++)); do
		if [[ -n "\${removed_words[i]-}" ]]; then
			[[ "$value_kind" == value ]] || value_kind=""
			continue
		fi
		token="\${argv[i]}"
		if ((i == cursor_index)) && [[ "$value_kind" == boolean && "$token" != -* ]]; then break; fi
		if [[ -n "$value_kind" ]] && ${funcName}_owns_operand "$token"; then
			((i == cursor_index)) && break
			first_variadic=0
			[[ "$value_kind" != variadic ]] && value_kind=""
			continue
		fi
		value_kind=""
		if ((i == cursor_index)); then
			if ${funcName}_option "$token" && [[ -n "$option_prefix" ]]; then
				value_flag="$option_spelling" value_kind="$option_kind" value_prefix="$option_prefix"
			fi
			break
		fi
		${funcName}_option "$token" && ${funcName}_start_operand
	done`);
	lines.push('');
}

function emitBashOptionHelpers(
	lines: string[],
	funcName: string,
	rootFlags: Readonly<Record<string, FlagSchema>>,
	nodes: readonly CommandNode[],
	parseOptions: CLISchema['flagSettings'],
	config: CLISchema['configSettings'],
	reservedOperands: readonly string[],
): void {
	lines.push(`${funcName}_flag() {
	case "$subcmd_path" in`);
	for (const { path, mergedFlags } of [{ path: [], mergedFlags: rootFlags }, ...nodes]) {
		const lookup = buildFlagLookup(mergedFlags, parseOptions);
		if (lookup.size === 0) continue;
		lines.push(`\t\t${quoteShellCasePattern(path.join(' '))})`);
		lines.push('\t\t\tcase "$1" in');
		for (const [spelling, entry] of lookup) {
			const long = escapeBashCasePatternValue(`--${spelling}`);
			const short = escapeBashCasePatternValue(`-${spelling}`);
			const takesValue = flagExpectsValue(entry.schema);
			const longKind = takesValue
				? entry.schema.variadic
					? 'variadic'
					: 'value'
				: !entry.negated && entry.schema.separateValue
					? 'boolean'
					: 'switch';
			const shortKind = takesValue ? 'value' : 'switch';
			const canonical = quoteShellArg(entry.negated ? '' : `--${entry.name}`);
			const setKind = (kind: string) =>
				`option_spelling=${canonical} option_kind=${kind}; return 0 ;;`;
			if (spelling.length === 1 && longKind === shortKind) {
				lines.push(`\t\t\t\t${long}|${short}) ${setKind(longKind)}`);
			} else {
				lines.push(`\t\t\t\t${long}) ${setKind(longKind)}`);
				if (spelling.length === 1) lines.push(`\t\t\t\t${short}) ${setKind(shortKind)}`);
			}
		}
		lines.push('\t\t\tesac');
		lines.push('\t\t\t;;');
	}
	lines.push(`	esac
	return 1
}

${funcName}_option() {
	local token="$1" short i
	option_prefix=""
	case "$token" in
		--) return 1 ;;
		--*)
			${funcName}_flag "\${token%%=*}" || return
			[[ "$token" == *=* ]] && option_prefix="\${token%%=*}="
			return 0
			;;
		-?*)
			short="\${token:1}"
			for ((i = 0; i < \${#short}; i++)); do
				${funcName}_flag "-\${short:i:1}" || return
				if [[ "$option_kind" == value ]]; then
					((i + 1 < \${#short})) && option_prefix="\${token:0:i+2}"
					break
				fi
			done
			return 0
			;;
	esac
	return 1
}

${funcName}_start_operand() {
	value_flag="$option_spelling" value_kind="$option_kind"
	first_variadic=0
	if [[ "$option_kind" == variadic ]]; then
		[[ -z "$option_prefix" ]] && first_variadic=1
	elif [[ -n "$option_prefix" || "$option_kind" == switch ]]; then
		value_kind=""
	fi
	return 0
}

${funcName}_owns_operand() {
	local token="$1"
	[[ "$token" == -- ]] && return 1
	if [[ "$value_kind" == boolean ]]; then
		[[ "$token" == true || "$token" == false || "$token" == 1 || "$token" == 0 ]]
		return
	fi
	[[ "$token" == - || "$token" != -* ]] && return 0
	((first_variadic)) || return 1`);
	if (config !== undefined || reservedOperands.length > 0) {
		lines.push(`	# A proposed standalone value would be subject to framework filtering.
	if (( $# > 1 )); then
		case "$token" in`);
		if (reservedOperands.length > 0) {
			lines.push(`\t\t\t${reservedOperands.join('|')}) return 1 ;;`);
		}
		if (config !== undefined) {
			lines.push('\t\t\t--config=?*) ((config_seen)) || return 1 ;;');
		}
		lines.push('\t\tesac');
		lines.push('\tfi');
	}
	lines.push(`	case "$token" in
		-h|--help|--help=all) return 1 ;;
		--*) ! ${funcName}_flag "\${token%%=*}" ;;
		*) ! ${funcName}_flag "\${token:0:2}" ;;
	esac
}

`);
}

function emitBashValueCompletions(
	lines: string[],
	funcName: string,
	flags: Readonly<Record<string, FlagSchema>>,
	indent: string,
	helpTopics: CommandSchema['helpTopics'],
): void {
	lines.push(`${indent}if [[ -n "$value_kind" ]]; then`);
	const topicFlags = new Set(Object.keys(helpTopics ?? {}).map((name) => `--help=${name}`));
	const candidates = Object.entries(flags).flatMap(([name, schema]) => {
		const values = acceptsArgv(schema) ? staticFlagCandidates(schema) : undefined;
		if (values === undefined) return [];
		const blockedTopics = schema.variadic ? values.filter((value) => topicFlags.has(value)) : [];
		return [{ name, values, blockedTopics }];
	});
	if (candidates.length > 0) {
		lines.push(`${indent}\tlocal enum_cur="\${cur#"$value_prefix"}"`);
		lines.push(`${indent}\tcase "$value_flag" in`);
		for (const { name, values, blockedTopics } of candidates) {
			lines.push(`${indent}\t\t${escapeBashCasePatternValue(`--${name}`)})`);
			lines.push(formatBashEnumCompletion(values, blockedTopics, `${indent}\t\t\t`, funcName));
			lines.push(`${indent}\t\t\t;;`);
		}
		lines.push(`${indent}\tesac`);
	}
	// Fall back to commands and flags when an optional boolean has no matching suggestion.
	lines.push(
		`${indent}\tif [[ "$value_kind" != boolean || -n "$value_prefix" ]] || ((\${#COMPREPLY[@]})) || ${funcName}_owns_operand "$cur"; then return 0; fi`,
	);
	lines.push(`${indent}fi`);
}

/** Filter framework flags after command operands have been marked. */
function emitBashPreflightFilter(
	lines: string[],
	funcName: string,
	config: CLISchema['configSettings'],
	outputPatterns: readonly string[],
): void {
	lines.push(`${funcName}_filter_preflight() {
	local i token`);
	if (config !== undefined) lines.push('\tconfig_seen=0 no_config_seen=0');
	lines.push(`
	for ((i = 0; i <= cursor_index; i++)); do
		token="\${argv[i]}"
		case "$token" in
			--) break ;;`);
	if (outputPatterns.length > 0) {
		lines.push(`			${outputPatterns.join('|')})
				removed_words[i]=1
				;;`);
	}
	if (config?.noConfigFlag === true) {
		lines.push(`			--no-config)
				no_config_seen=1
				removed_words[i]=1
				;;`);
	}
	if (config !== undefined) {
		lines.push(`			--config=*)
				((config_seen)) && continue
				if [[ "$token" != --config= ]]; then
					config_seen=1
				elif ((i != cursor_index)); then
					continue
				fi
				removed_words[i]=1
				;;
			--config)
				((!config_seen && i < cursor_index)) || continue
				[[ "\${argv[i+1]}" != -* ]] || continue
				config_seen=1
				removed_words[i]=1
				((++i))
				removed_words[i]=1
				;;`);
	}
	lines.push(`		esac
	done
}

`);
}

/** Rescan argv at each dispatch level and retain the nearest action for positional fallback. */
function emitBashPathDetection(
	lines: string[],
	funcName: string,
	visibleCommands: readonly CommandSchema[],
	nodes: readonly CommandNode[],
	hasPreflight: boolean,
): void {
	lines.push(`${funcName}_subcommand() {
	local subcmd_path="$1"
	case "$subcmd_path" in`);
	for (const { path, children } of [{ path: [], children: visibleCommands }, ...nodes]) {
		if (children.length === 0) continue;
		lines.push(`\t\t${quoteShellCasePattern(path.join(' '))})`);
		lines.push('\t\t\tcase "$2" in');
		for (const child of children) {
			const patterns = [child.name, ...child.aliases].map(escapeBashCasePatternValue);
			const parentPath = path.length > 0 ? '$subcmd_path ' : '';
			const childPath = `"${parentPath}${escapeBashDoubleQuotedValue(child.name)}"`;
			const hasChildren = child.commands.some((command) => !command.hidden) ? 1 : 0;
			lines.push(`\t\t\t\t${patterns.join('|')})`);
			lines.push(`\t\t\t\t\tsubcmd_path=${childPath}`);
			lines.push(
				`\t\t\t\t\tnext_path="$subcmd_path" next_has_children=${hasChildren} next_has_action=${child.hasAction ? 1 : 0}`,
			);
			lines.push('\t\t\t\t\treturn 0 ;;');
		}
		lines.push('\t\t\tesac');
		lines.push('\t\t\t;;');
	}
	lines.push(`	esac
	return 1
}

${funcName}_route() {
	local subcmd_path="" i token next_path next_has_children next_has_action fallback_path=""
	local -a tentative_commands=()
	local option_spelling option_kind option_prefix
	local value_flag value_kind first_variadic
	resolved_path=""
	removed_words=()`);
	if (hasPreflight) lines.push(`\t${funcName}_filter_preflight`);
	lines.push(`	while :; do
		for ((i = 0; i < cursor_index; i++)); do
			[[ -n "\${removed_words[i]-}" ]] && continue
			token="\${argv[i]}"
			if [[ "$token" != -* ]]; then
				if ! ${funcName}_subcommand "$subcmd_path" "$token"; then
					if [[ -n "$token" && -n "$fallback_path" ]]; then
						resolved_path="$fallback_path"
						for i in "\${tentative_commands[@]}"; do unset 'removed_words[i]'; done
					fi
					return 0
				fi
				removed_words[i]=1
				resolved_path="$next_path"
				((next_has_children)) || return 0
				if ((next_has_action)); then
					fallback_path="$next_path"
					tentative_commands=()
				else
					tentative_commands+=("$i")
				fi
				subcmd_path="$next_path"
				continue 2
			fi
			${funcName}_option "$token" || continue
			${funcName}_start_operand
			if [[ "$value_kind" == value ]]; then
				while [[ -n "\${removed_words[i+1]-}" ]]; do ((++i)); done
				((++i))
				continue
			fi
			[[ -n "$value_kind" ]] || continue
			while ((i + 1 < cursor_index)) && [[ -z "\${removed_words[i+1]-}" ]]; do
				${funcName}_owns_operand "\${argv[i+1]}" || break
				((++i))
				first_variadic=0
				[[ "$value_kind" == variadic ]] || break
			done
		done
		return 0
	done
}

`);
}

/**
 * Escape a string for use as a bash `case` pattern.
 *
 * Escapes glob metacharacters so arbitrary command, alias, and flag names are
 * matched literally rather than being interpreted as shell patterns.
 *
 * @internal
 */
function quoteShellCasePattern(pattern: string): string {
	if (pattern === '') return "''";
	if (pattern.includes(' ')) return `"${escapeBashDoubleQuotedValue(pattern)}"`;
	return escapeBashCasePatternValue(pattern);
}

/**
 * Escape a value for use in a bash `case` pattern.
 *
 * Escapes glob metacharacters so arbitrary command and flag names are matched
 * literally rather than being interpreted as shell patterns.
 *
 * @internal
 */
function escapeBashCasePatternValue(value: string): string {
	if (/^[a-zA-Z0-9_\-.]+$/.test(value)) return value;
	return value
		.replace(/\\/g, '\\\\')
		.replace(/'/g, "\\'")
		.replace(/"/g, '\\"')
		.replace(/[$`;&<>]/g, '\\$&')
		.replace(/\|/g, '\\|')
		.replace(/\*/g, '\\*')
		.replace(/\?/g, '\\?')
		.replace(/\[/g, '\\[')
		.replace(/\]/g, '\\]')
		.replace(/\(/g, '\\(')
		.replace(/\)/g, '\\)')
		.replace(/\{/g, '\\{')
		.replace(/\}/g, '\\}')
		.replace(/\+/g, '\\+')
		.replace(/!/g, '\\!')
		.replace(/@/g, '\\@')
		.replace(/#/g, '\\#')
		.replace(/~/g, '\\~')
		.replace(/\s/g, (match) => (match === ' ' ? '\\ ' : `\\${match}`));
}

/**
 * Escape a value for interpolation inside a bash double-quoted string.
 *
 * @internal
 */
function escapeBashDoubleQuotedValue(value: string): string {
	return value
		.replace(/\\/g, '\\\\')
		.replace(/"/g, '\\"')
		.replace(/\$/g, '\\$')
		.replace(/`/g, '\\`');
}

/**
 * Escape a string for safe embedding inside an existing single-quoted
 * shell literal (e.g. inside `compgen -W '...'`).
 *
 * Uses the `'\''` idiom: close quote, escaped literal quote, reopen
 * quote. Returns the input unchanged when it consists only of shell-safe
 * characters, which covers the vast majority of flag/command names.
 *
 * @internal
 */
function escapeForSingleQuote(value: string): string {
	if (/^[a-zA-Z0-9_\-.]+$/.test(value)) return value;
	return value.replace(/'/g, "'\\''");
}

/** Match static values literally and pass full tokens to the Readline helper. */
function formatBashEnumCompletion(
	values: readonly string[],
	blockedTopics: readonly string[],
	indent: string,
	funcName: string,
): string {
	const words = values.every((value) => /^[a-zA-Z0-9_\-.]+$/.test(value))
		? values.join(' ')
		: values.map((value) => `$'${escapeBashDollarQuote(value)}'`).join(' ');
	const topicGuard =
		blockedTopics.length === 0
			? []
			: [
					`${indent}\tif [[ -z "$value_prefix" ]]; then`,
					`${indent}\t\tcase "$candidate" in`,
					`${indent}\t\t\t${blockedTopics.map(escapeBashCasePatternValue).join('|')}) continue ;;`,
					`${indent}\t\tesac`,
					`${indent}\tfi`,
				];
	return [
		`${indent}local candidate`,
		`${indent}for candidate in ${words}; do`,
		`${indent}\t[[ "$candidate" == "$enum_cur"* ]] || continue`,
		...topicGuard,
		`${indent}\t[[ -n "$value_prefix" ]] || ${funcName}_owns_operand "$candidate" candidate || continue`,
		`${indent}\t${funcName}_reply "$value_prefix$candidate"`,
		`${indent}done`,
	].join('\n');
}

/**
 * Escape a single enum value for use inside a bash `$'...'` string.
 *
 * In `$'...'` context:
 * - `\\` → literal backslash
 * - `\'` → literal single quote
 * - `\n` → newline (used as IFS delimiter, so must be escaped in values)
 *
 * Values that are simple identifiers pass through unescaped.
 *
 * @internal
 */
function escapeBashDollarQuote(value: string): string {
	return value.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n');
}

/**
 * Collect all `--flag` words (long + short aliases + visible negated
 * spellings) for a flag record.
 *
 * @internal
 */
function collectFlagWords(flags: Readonly<Record<string, FlagSchema>>): string {
	const words: string[] = [];
	for (const [name, schema] of Object.entries(flags)) {
		if (!acceptsArgv(schema)) continue;
		words.push(`--${name}`);
		for (const alias of getFlagAliasNames(schema)) {
			words.push(alias.length === 1 ? `-${alias}` : `--${alias}`);
		}
		const negated = getVisibleNegatedName(name, schema);
		if (negated !== undefined) {
			words.push(`--${negated}`);
		}
	}
	return words.join(' ');
}

function dedupeWords(words: readonly string[]): readonly string[] {
	return [...new Set(words)];
}

